-- Other Adjustments Query
SELECT
    CEBA.BILL_ID,
    NVL(CEBA.TOT_ADJ_AMT, 0) 
      + NVL(CEBSPD_AGG.TOT_CM_TOT_COV_AMT, 0) 
      + NVL(CEBSPC_AGG.TOT_AMT, 0) 
      + NVL(CEBSND_AGG.TOT_CM_TOT_COV_AMT, 0) 
      + NVL(CEBSNC_AGG.TOT_AMT, 0) AS TOTAL_OTHER_ADJ,
    ROW_NUMBER() OVER (
      PARTITION BY CEB.BILL_ID
      ORDER BY
        CEB.CM_EXT_SEQ_NUM DESC
    ) RN
FROM BILLING_OWNER.CM_EXTR_BILL_ACCT CEBA
LEFT OUTER JOIN BILLING_OWNER.CM_EXTR_BILL CEB ON CEBA.BILL_ID = CEB.BILL_ID
LEFT OUTER JOIN (
    SELECT BILL_ID, SUM(CM_TOT_COV_AMT) AS TOT_CM_TOT_COV_AMT
    FROM BILLING_OWNER.CM_EXTR_BILL_SUB_PREM_DTL
    WHERE CM_RETRO_SW = 'Y'
    GROUP BY BILL_ID
) CEBSPD_AGG ON CEBA.BILL_ID = CEBSPD_AGG.BILL_ID
LEFT OUTER JOIN (
    SELECT BILL_ID, SUM(TOT_AMT) AS TOT_AMT
    FROM BILLING_OWNER.CM_EXTR_BILL_SUB_PREM_CORR
    WHERE CM_RETRO_SW = 'Y'
    GROUP BY BILL_ID
) CEBSPC_AGG ON CEBA.BILL_ID = CEBSPC_AGG.BILL_ID
LEFT OUTER JOIN (
    SELECT BILL_ID, SUM(CM_TOT_COV_AMT) AS TOT_CM_TOT_COV_AMT
    FROM BILLING_OWNER.CM_EXTR_BILL_SUB_NONPREM_DTL
    WHERE CM_RETRO_SW = 'Y'
      AND CHRG_DESCR NOT IN (
        'APTC Subsidy',
        'APTC Offset Subsidy',
        'APTC',
        'State Subsidy',
        'State Offset Subsidy'
      )
      AND CHRG_DESCR NOT LIKE '%APTC%'
    GROUP BY BILL_ID
) CEBSND_AGG ON CEBA.BILL_ID = CEBSND_AGG.BILL_ID
LEFT OUTER JOIN (
    SELECT BILL_ID, SUM(TOT_AMT) AS TOT_AMT
    FROM BILLING_OWNER.CM_EXTR_BILL_SUB_NONPREM_CORR
    WHERE CM_RETRO_SW = 'Y'
      AND CHRG_DESCR NOT IN (
        'APTC Subsidy',
        'APTC Offset Subsidy',
        'APTC',
        'State Subsidy',
        'State Offset Subsidy'
      )
      AND CHRG_DESCR NOT LIKE '%APTC%'
    GROUP BY BILL_ID
) CEBSNC_AGG ON CEBA.BILL_ID = CEBSNC_AGG.BILL_ID
WHERE 
CEBA.BILL_ID = '829812754937'; -- BILL ID from PERF