SELECT /*+PARALLEL(16)*/ T.ACCT_ID, T.BILL_ID, T.BILL_DT, T.ENTITY_NAME
, LISTAGG(CASE WHEN T.CHRG_DESCR='APTC Subsidy' THEN (T.COVERGAE_PERIOD||'='||T.SNPD_CM_TOT_COV_AMT) END, ', ') WITHIN GROUP (ORDER BY T.BILL_ID) FEDERAL_RETRO_DETAIL
, LISTAGG(CASE WHEN T.CHRG_DESCR='State Subsidy' THEN (T.COVERGAE_PERIOD||'='||T.SNPD_CM_TOT_COV_AMT) END, ', ') WITHIN GROUP (ORDER BY T.BILL_ID) STATE_RETRO_DETAIL
FROM (
SELECT AC.ACCT_ID, BL.BILL_ID, BL.BILL_DT, BR.BATCH_NBR
, EBS.ENTITY_NAME, EBSNPD.CHRG_DESCR
, CASE WHEN EBSNPD.START_DT IS NOT NULL THEN (TO_CHAR(EBSNPD.START_DT, 'MON') ||'-'|| EXTRACT(YEAR FROM EBSNPD.START_DT)) ELSE NULL END COVERGAE_PERIOD
, SUM(EBSNPD.CM_TOT_COV_AMT) SNPD_CM_TOT_COV_AMT
FROM BILLING_OWNER.CI_ACCT AC, BILLING_OWNER.CI_BILL BL, BILLING_OWNER.CI_BILL_ROUTING BR
, BILLING_OWNER.CM_EXTR_BILL_SUB EBS
LEFT JOIN BILLING_OWNER.CM_EXTR_BILL_SUB_NONPREM_DTL EBSNPD ON EBSNPD.BILL_ID=EBS.BILL_ID AND EBSNPD.CM_RETRO_SW='Y' AND EBSNPD.CM_EXT_SEQ_NUM=EBS.CM_EXT_sEQ_NUM 
    AND EBSNPD.POLICY_ID=EBS.POLICY_ID AND EBSNPD.PLAN_ID=EBS.PLAN_ID AND EBSNPD.MEMBERSHIP_ID=EBS.MEMBERSHIP_ID
    AND EBSNPD.CHRG_DESCR IN ('APTC Subsidy', 'State Subsidy')
WHERE 0=0 AND AC.ACCT_ID=BL.ACCT_ID AND BL.BILL_ID=BR.BILL_ID AND BR.BATCH_CD='CM-BILEX'
AND BL.BILL_ID=EBS.BILL_ID AND EBS.CM_EXT_SEQ_NUM=(SELECT MAX(EBS1.CM_EXT_SEQ_NUM) FROM BILLING_OWNER.CM_EXTR_BILL_BATCH_RUN EBS1 WHERE EBS1.BILL_ID=EBS.BILL_ID)
AND BR.BATCH_NBR=:batch
GROUP BY AC.ACCT_ID, BL.BILL_ID, BL.BILL_DT, BR.BATCH_NBR, EBS.ENTITY_NAME, EBSNPD.CHRG_DESCR, EBSNPD.START_DT
, (TO_CHAR(EBSNPD.START_DT, 'MON')||'-'|| EXTRACT(YEAR FROM EBSNPD.START_DT))
) T WHERE 0=0 AND T.COVERGAE_PERIOD IS NOT NULL
GROUP BY T.ACCT_ID, T.BILL_ID, T.BILL_DT, T.ENTITY_NAME
