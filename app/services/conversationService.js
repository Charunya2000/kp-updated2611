'use server';

import axios from 'axios';
import FormData from 'form-data';
import { getServerSession } from '@utils/getSession';
import { selectSource } from './sourceService';

export const callWorkflowService2 = async (formData) => {
  try {
    // Extract fields from the incoming FormData
    const path = formData.get('path');
    const query = formData.get('query');
    const { nuid } = await getServerSession();
    const filter = formData.get('filter');
    const files = formData.getAll('files'); // Get all files under the 'files' key

    // Create a new FormData instance for the Medicaid service call
    const newFormData = new FormData();
    newFormData.append('query', query);
    newFormData.append('nuid', nuid); // Pass the query as-is
    newFormData.append('filter', filter || 'latest');

    // Append all files to the new FormData
    for (const file of files) {
      if (file.arrayBuffer) {
        // Convert File to Buffer
        const buffer = Buffer.from(await file.arrayBuffer());
        newFormData.append('files', buffer, file.name); // Append Buffer with its name
      } else if (file instanceof Buffer) {
        newFormData.append('files', file, file.name || 'unknown-file'); // Append Buffer directly
      } else if (file?.pipe) {
        // If the file is a stream
        newFormData.append('files', file, file.name || 'unknown-file');
      } else {
        throw new Error('Unsupported file format');
      }
    }

    const ORCHESTRATION_APP_URL = process.env.ORCHESTRATION_APP_URL;
    // Make the POST request to the Medicaid service using axios
    const response = await axios.post(
      `${ORCHESTRATION_APP_URL}/${path}`,
      newFormData,
      {
        headers: {
          ...newFormData.getHeaders(), // Include headers generated by FormData
        },
      }
    );

    return response.data;
  } catch (error) {
    console.error('Error:', error.response ? error.response.data : error.message);
    throw error;
  }
};

export const callProductsWorkflowService = async (formData, teamName) => {
  try {
    // Extract fields from the incoming FormData
    const path = formData.get('path');
    const query = formData.get('query');
    const smartNoteId = formData.get('smartNoteId');
    const { nuid } = await getServerSession();
    const filter = formData.get('filter');
    const sources = formData.getAll('sources'); // Get all source IDs under the 'sourceIds' key

    // get all the actual sources from sourceIds
    const sourceItems = JSON.parse(sources);
    let actualSources = [];
    for (const source of sourceItems) {
      if (source.sourceType === 'UploadedDocument') {
        const actual = await selectSource({ nuid: nuid, id: source.sourceId, type: 'UploadedDocument', parentId: source.parentId }, teamName);
        actualSources.push(actual);
      }
    }

    // map just the file name/extension
    actualSources = actualSources.map((source) => {
      const extension = source.fileName.split('.').pop();
      if (extension === 'pptx' || extension === 'xlsx' || extension === 'ppt') {
        return source.fileName;
      }
    });

    // Create a new FormData instance for the Products service call
    const newFormData = new FormData();
    // query is already a JSON string, when stringify it will double-encode it
    const queryObj = typeof query === 'string' ? JSON.parse(query) : query;

    newFormData.append('query', JSON.stringify({
      ...queryObj,
      smartnote_id: smartNoteId,
      nuid: nuid,
      filter: 'latest',
      document_list: actualSources
    }));


    const ORCHESTRATION_APP_URL = process.env.ORCHESTRATION_APP_URL;
    // Make the POST request to the Products service using axios
    const response = await axios.post(
      `${ORCHESTRATION_APP_URL}/${path}`,
      newFormData,
      {
        headers: {
          ...newFormData.getHeaders(), // Include headers generated by FormData
        },
      }
    );

    return response.data;
  } catch (error) {
    console.error('Error:', error.response ? error.response.data : error.message);
    throw error;
  }
}