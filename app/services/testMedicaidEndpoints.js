'use server';

import axios from 'axios';
import FormData from 'form-data';
import fs from 'fs'; // To read the file

const postToImageExtract = async () => {
  try {
    // Create a FormData instance
    const formData = new FormData();
    formData.append(
      'query',
      JSON.stringify({
        query: 'Extract requirements from this file.', // Replace with your actual query
        filter: 'latest',
      })
    );
    formData.append('file', fs.createReadStream('Immunization.pdf')); // Replace ***file**path*** with the actual file path

    // Make the POST request
    const ORCHESTRATION_APP_URL = process.env.ORCHESTRATION_APP_URL;
    const response = await axios.post(
      `${ORCHESTRATION_APP_URL}/medicaid/changeReq`,
      formData,
      {
        headers: {
          ...formData.getHeaders(), // Include headers generated by FormData
        },
      }
    );

    console.log('Response:', response.data);
  } catch (error) {
    console.error('Error:', error.response ? error.response.data : error.message);
  }
};

// Call the function
postToImageExtract();