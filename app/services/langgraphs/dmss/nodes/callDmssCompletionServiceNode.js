export const callDmssCompletionServiceNode = async (state) => {
  try {
    const body = {
      query: { query: state.chatInteraction.prompt, filter: 'latest' },
      smartnote_id: { smartnote_id: state.smartNoteId },
      assignment_sheet: state.assignmentSheet ? [state.assignmentSheet.fileName] : [""],
      letters: state.letters ? state.letters.map(letter => letter.fileName) : [""],
      uploaded_notes: state.uploadedNotes ? state.uploadedNotes.map(note => note.fileName) : [""],
      test_case_templates: state.testCaseTemplates ? state.testCaseTemplates.map(template => template.fileName) : [""],
      saved_notes: state.savedNotesContent ? state.savedNotesContent : [""],
      saved_responses: state.savedResponsesContent ? state.savedResponsesContent : [""],
      messages: state?.totalMessages && state.totalMessages.length > 0 ? state.totalMessages : [{ "role": "assistant", "content": "" }],
      assignment_sheet_exists: !!state.assignmentSheetExists,
      letters_exists: !!state.lettersExists,
      test_case_templates_exists: !!state.testCaseTemplatesExists
    };

    // Make the POST request to the External Completions service using fetch
    const ORCHESTRATION_APP_URL = process.env['ORCHESTRATION_APP_URL'];
    const response = await fetch(`${ORCHESTRATION_APP_URL}/api/dmss/rag`, {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        'Accept': 'application/json'
      },
      body: JSON.stringify(body),
    });

    const json = await response.json();

    if (!response.ok) {
      state.sendEvent({ type: 'data', data: json.message || "Something went wrong while I was processing your request. Please try again. If this issue persists, contact HealthPlanAIServices@kp.org." });
      return;
    }

    if (json.response) {
      state.sendEvent({ type: 'data', data: json.response });
    } else {
      throw new Error("DMSS API Error: No response received from the service");
    }

    return;
  } catch (error) {
    console.error('Error:', error.response ? error.response.data : error.message);
    state.sendEvent({ type: 'data', data: "Something went wrong while I was processing your request. Please try again. If this issue persists, contact HealthPlanAIServices@kp.org." });
  }
};

