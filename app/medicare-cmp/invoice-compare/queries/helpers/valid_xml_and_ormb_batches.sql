WITH BILL_SCOPE AS (
  SELECT DISTINCT BR.BILL_ID,
                  BR.BATCH_NBR
    FROM BILLING_OWNER.CI_BILL_ROUTING BR
   WHERE BR.BATCH_CD = 'CM-BILEX'
),PAYLOAD AS (
  SELECT EPL.KPMC_TRANSACTION_ID,
         B.BILL_ID,
         B.RGN_CD,
         B.BATCH_CD,
         B.BATCH_NBR,
         EPL.PAYLOAD_XML,
         ROW_NUMBER()
         OVER(PARTITION BY B.KPMC_INDIVIDUAL_INVOICE_TRANSACTION_ID,
                           B.BILL_ID
              ORDER BY B.STM_SEQ_NM DESC,
                       EPL.INSERT_TIMESTAMP DESC
         ) AS RN
    FROM KPMC_DOCMGMT_ADM.KPMC_EXTRACT_PAYLOAD EPL
    JOIN KPMC_DOCMGMT_ADM.INDV_INVOICE_CONS_CTL B
  ON B.KPMC_INDIVIDUAL_INVOICE_TRANSACTION_ID = EPL.KPMC_TRANSACTION_ID
   WHERE EPL.TYPE = 'INDV_CONS_CBILL'
     AND B.BATCH_CD = 'CM-STMEX'
)
SELECT X.BATCH_NBR,
       X.BILL_ID,
       X.PBILL_ID,
       X.KPMC_TRANSACTION_ID,
       X.PAYLOAD_XML
  FROM (
  SELECT BS.BATCH_NBR,
         BS.BILL_ID,
         P.BILL_ID AS PBILL_ID,
         P.KPMC_TRANSACTION_ID,
         P.PAYLOAD_XML,
         ROW_NUMBER()
         OVER(PARTITION BY BS.BATCH_NBR
              ORDER BY P.KPMC_TRANSACTION_ID,
                       BS.BILL_ID
         ) AS BATCH_RN
    FROM BILL_SCOPE BS
    JOIN PAYLOAD P
  ON P.BILL_ID = BS.BILL_ID
   WHERE P.RN = 1
) X
 WHERE X.BATCH_RN = 1
 ORDER BY X.BATCH_NBR;