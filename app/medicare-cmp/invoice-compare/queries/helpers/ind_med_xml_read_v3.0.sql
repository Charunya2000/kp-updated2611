,PAST_DUE_COMPARE AS (
  SELECT KPMC_TRANSACTION_ID,
         BILL_ID,
         REGION,
         BATCH_NBR,
         'PAST_DUE' AS ENTITY_TYPE,
         ENTITY_KEY,
         FIELD_NAME,
         FIELD_VALUE
    FROM (
    SELECT X.KPMC_TRANSACTION_ID,
           X.BILL_ID,
           X.BATCH_NBR,
           X.REGION,
           X.BASE_ENTITY_KEY
           || ':'
           || TO_CHAR(ROW_NUMBER()
                      OVER(PARTITION BY X.KPMC_TRANSACTION_ID,
                                        X.BILL_ID,
                                        X.BATCH_NBR,
                                        X.BASE_ENTITY_KEY
                           ORDER BY TO_NUMBER(X.PAST_DUE_AMOUNT)
           )) AS ENTITY_KEY,
           X.PAST_DUE_COVERAGE_PERIOD,
           X.PAST_DUE_DUE_DATE,
           X.PAST_DUE_AMOUNT
      FROM (
      SELECT KPMC_TRANSACTION_ID,
             BILL_ID,
             BATCH_NBR,
             TRIM(REGION) AS REGION,
             SUBSCRIBER_KEY
             || ':'
             || NVL(
               SUBSTR(
                 TO_CHAR(
                   TO_DATE(PAST_DUE_COVERAGE_PERIOD,
                         'MM/DD/YYYY'),
                   'YYYY-MM-DD'
                 ),
                 1,
                 7
               ),
               'NULL'
             )
             || ':'
             || NVL(
               TO_CHAR(
                 TO_DATE(PAST_DUE_DUE_DATE,
                       'MM/DD/YYYY'),
                 'YYYY-MM-DD'
               ),
               'NULL'
             ) AS BASE_ENTITY_KEY,
             TO_CHAR(
               TO_DATE(PAST_DUE_COVERAGE_PERIOD,
                     'MM/DD/YYYY'),
               'YYYY-MM-DD'
             ) AS PAST_DUE_COVERAGE_PERIOD,
             TO_CHAR(
               TO_DATE(PAST_DUE_DUE_DATE,
                     'MM/DD/YYYY'),
               'YYYY-MM-DD'
             ) AS PAST_DUE_DUE_DATE,
             TO_CHAR(
               TO_NUMBER(PAST_DUE_AMOUNT),
               'FM9999999990D00'
             ) AS PAST_DUE_AMOUNT
        FROM PAST_DUE_ROWS
    ) X
  ) UNPIVOT INCLUDE NULLS ( FIELD_VALUE
    FOR FIELD_NAME
  IN ( PAST_DUE_COVERAGE_PERIOD AS 'PAST-DUE-COVERAGE-PERIOD',
       PAST_DUE_DUE_DATE AS 'PAST-DUE-DUE-DATE',
       PAST_DUE_AMOUNT AS 'PAST-DUE-AMOUNT' ) )
)
