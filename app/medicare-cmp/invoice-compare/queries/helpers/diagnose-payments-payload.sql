-- Diagnostic query to find BATCH_NBR with both PAYLOAD_XML and PAYMENT data
WITH INDMEDSTM AS (
  SELECT SBR.STM_ID,
         SBR.BATCH_NBR,
         CES.BILL_ID,
         STM.STM_DT
    FROM CM_EXTR_STM_BATCH_RUN SBR
    JOIN CM_EXTR_STM_DTL CES
  ON SBR.STM_ID = CES.STM_ID
     AND SBR.CM_EXT_SEQ_NUM = (
    SELECT MAX(CM_EXT_SEQ_NUM)
      FROM CM_EXTR_STM_BATCH_RUN SBR1
     WHERE SBR1.STM_ID = SBR.STM_ID
  )
     AND CES.CM_EXT_SEQ_NUM = (
    SELECT MAX(CM_EXT_SEQ_NUM)
      FROM CM_EXTR_STM_DTL CES1
     WHERE CES1.STM_ID = SBR.STM_ID
       AND CES1.BILL_ID = CES.BILL_ID
  )
     AND SBR.BATCH_CD = 'CM-STMEX'
    JOIN CI_ACCT ACT
  ON ACT.ACCT_ID = CES.ACCT_ID
     AND ACT.CIS_DIVISION = 'GOV'
    JOIN CI_STM STM
  ON STM.STM_ID = SBR.STM_ID
),WITH_PAYLOAD AS (
  SELECT DISTINCT A.STM_ID,
                  A.BATCH_NBR,
                  A.BILL_ID,
                  A.STM_DT,
                  'YES' AS HAS_PAYLOAD_XML
    FROM INDMEDSTM A
   INNER JOIN KPMC_DOCMGMT_ADM.KPMC_EXTRACT_PAYLOAD B
  ON A.STM_ID = B.KPMC_TRANSACTION_ID
),PAYMENT_SUMMARY AS (
  SELECT WP.BATCH_NBR,
         WP.BILL_ID,
         COUNT(DISTINCT EBP.PAY_DT) AS PAYMENT_RECORD_COUNT,
         SUM(EBP.PAY_AMT) AS TOTAL_PAYMENT_AMOUNT,
         MIN(EBP.PAY_DT) AS EARLIEST_PAYMENT_DATE,
         MAX(EBP.PAY_DT) AS LATEST_PAYMENT_DATE,
         COUNT(DISTINCT
           CASE
             WHEN EBP.PAY_STATUS_FLG = '60' THEN
               1
           END
         ) AS STATUS_60_COUNT,
         COUNT(DISTINCT
           CASE
             WHEN EBP.PAY_STATUS_FLG != '60' THEN
               1
           END
         ) AS OTHER_STATUS_COUNT
    FROM WITH_PAYLOAD WP
    LEFT JOIN CM_EXTR_BILL_PAY EBP
  ON WP.BILL_ID = EBP.BILL_ID
   GROUP BY WP.BATCH_NBR,
            WP.BILL_ID
)
SELECT PS.BATCH_NBR,
       (
         SELECT P.PAYLOAD_XML
           FROM WITH_PAYLOAD WP_INNER
          INNER JOIN KPMC_DOCMGMT_ADM.KPMC_EXTRACT_PAYLOAD P
         ON WP_INNER.STM_ID = P.KPMC_TRANSACTION_ID
          WHERE WP_INNER.BATCH_NBR = PS.BATCH_NBR
            AND ROWNUM = 1
       ) AS PAYLOAD_XML,
       COUNT(DISTINCT PS.BILL_ID) AS BILL_COUNT,
       SUM(
         CASE
           WHEN PS.PAYMENT_RECORD_COUNT > 0 THEN
             1
           ELSE
             0
         END
       ) AS BILLS_WITH_PAYMENTS,
       SUM(
         CASE
           WHEN PS.PAYMENT_RECORD_COUNT > 0
              AND PS.OTHER_STATUS_COUNT > 0 THEN
             1
           ELSE
             0
         END
       ) AS BILLS_WITH_VALID_PAYMENTS,
       SUM(PS.TOTAL_PAYMENT_AMOUNT) AS TOTAL_PAYMENTS_AMOUNT,
       MAX(PS.LATEST_PAYMENT_DATE) AS MOST_RECENT_PAYMENT
  FROM PAYMENT_SUMMARY PS
 GROUP BY PS.BATCH_NBR
 ORDER BY BILLS_WITH_VALID_PAYMENTS DESC,
          PS.BATCH_NBR;