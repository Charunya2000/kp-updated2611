-- Final comparison result table
--------------------------------------------------------------------------------

BEGIN
  EXECUTE IMMEDIATE 'DROP TABLE COMPARE_OWNER.MEDICARE_CMP_RESULTS PURGE';
EXCEPTION
  WHEN OTHERS THEN
    IF SQLCODE != -942 THEN
      RAISE;
    END IF;
END;
/
CREATE TABLE COMPARE_OWNER.MEDICARE_CMP_RESULTS (
  RUN_ID              NUMBER(13,0) NOT NULL,
  BATCH_NBR           NUMBER NOT NULL,
  KPMC_TRANSACTION_ID VARCHAR2(100) NOT NULL,
  BILL_ID             VARCHAR2(30) NOT NULL,
  REGION              VARCHAR2(10),
  ENTITY_TYPE         VARCHAR2(20) NOT NULL,
  ENTITY_KEY          VARCHAR2(100) NOT NULL,
  FIELD_NAME          VARCHAR2(100) NOT NULL,
  MEDICARE_VALUE      VARCHAR2(256),
  ORMB_VALUE          VARCHAR2(256),
  MATCH_STATUS        VARCHAR2(20) NOT NULL,
  CREATED_TS          TIMESTAMP DEFAULT SYSTIMESTAMP,
  CONSTRAINT CK_MEDICARE_CMP_RESULTS_MATCH CHECK ( MATCH_STATUS IN ( 'PASS',
                                                                     'FAIL' ) )
);


SELECT *
  FROM COMPARE_OWNER.MEDICARE_CMP_RESULTS;

