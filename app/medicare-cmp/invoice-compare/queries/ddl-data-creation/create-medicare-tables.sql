-- Run status table: procedure progress tracking
--------------------------------------------------------------------------------
BEGIN
  EXECUTE IMMEDIATE 'DROP TABLE COMPARE_OWNER.MEDICARE_CMP_RUN_STATUS PURGE';
EXCEPTION
  WHEN OTHERS THEN
    IF SQLCODE != -942 THEN
      RAISE;
    END IF;
END;
/
CREATE TABLE COMPARE_OWNER.MEDICARE_CMP_RUN_STATUS (
  RUN_ID             NUMBER(13,0) NOT NULL,
  BATCH_NBR          NUMBER NOT NULL,
  STATUS             VARCHAR2(100) NOT NULL,
  CURRENT_STEP       VARCHAR2(200),
  NEXT_STEP          VARCHAR2(200),
  ERROR_MESSAGE      VARCHAR2(1000),
  INVOICES_MED       NUMBER DEFAULT 0,
  TOTAL_RECORDS_ORMB NUMBER DEFAULT 0,
  TOTAL_COMPARE_MED  NUMBER DEFAULT 0,
  START_TS           TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  LAST_UPDATE_TS     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  END_TS             TIMESTAMP,
  CONSTRAINT PK_MEDICARE_CMP_RUN_STATUS PRIMARY KEY ( RUN_ID,
                                                      BATCH_NBR )
);


SELECT *
  FROM COMPARE_OWNER.MEDICARE_CMP_RUN_STATUS;

