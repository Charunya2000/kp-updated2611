-- with pivoted field columns: SOURCE_{FIELD_NAME}, TARGET_{FIELD_NAME}, {FIELD_NAME}_MATCH
WITH source_results AS (
  SELECT RUN_ID,
         BATCH_NBR,
         KPMC_TRANSACTION_ID,
         BILL_ID,
         REGION,
         FIELD_NAME,
         MATCH_STATUS
    FROM COMPARE_OWNER.MEDICARE_CMP_RESULTS
   WHERE BATCH_NBR = :BATCHNBR
     AND RUN_ID = :RUNID
),
aggregated_results AS (
  SELECT RUN_ID,
         BATCH_NBR,
         KPMC_TRANSACTION_ID,
         BILL_ID,
         REGION,
         FIELD_NAME,
         CASE
           WHEN MAX(CASE WHEN MATCH_STATUS = 'FAIL' THEN 1 ELSE 0 END) = 1 THEN
             'FAIL'
           ELSE
             'PASS'
         END AS MATCH_STATUS
    FROM source_results
   GROUP BY RUN_ID,
            BATCH_NBR,
            KPMC_TRANSACTION_ID,
            BILL_ID,
            REGION,
            FIELD_NAME
),
