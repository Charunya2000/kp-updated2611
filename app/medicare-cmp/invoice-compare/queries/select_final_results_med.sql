          ORDER BY ENTITY_TYPE,
                   ENTITY_KEY,
                   CREATED_TS,
                   RESULT_ROWID) AS MEDICARE_VALUE,
         LISTAGG(NVL(ORMB_VALUE, '<NULL>'), ', ') WITHIN GROUP(
          ORDER BY ENTITY_TYPE,
                   ENTITY_KEY,
                   CREATED_TS,
                   RESULT_ROWID) AS ORMB_VALUE,
         CASE WHEN MAX(CASE WHEN MATCH_STATUS = 'FAIL' THEN 1 ELSE 0 END) = 1 THEN 'FAIL' ELSE 'PASS' END AS MATCH_STATUS
    FROM SOURCE_RESULTS
