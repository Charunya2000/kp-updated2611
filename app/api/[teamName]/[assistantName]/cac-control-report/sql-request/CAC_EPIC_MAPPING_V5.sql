WITH CAC_CORRECT_MARKET_SEGMENT_DIVISIONS AS (
  SELECT
    REGION_CODE,
    REGIONAL_CUSTOMER_ID,
    MARKET_SEGMENT_DIVISION_CODE,
    MARKET_SEGMENT_SUBTYPE_CODE,
    MARKET_SEGMENT_TYPE_CODE,
    NAME AS REGIONAL_CUSTOMER_NAME
  FROM
    CUSTOMER_OWNER.CAC_REGIONAL_CUSTOMER -- WHERE MARKET_SEGMENT_DIVISION_CODE = 'Group'
),
CAC_MAX_VERSION AS (
  SELECT
    CCV.CONTRACT_ID,
    CCV.REGIONAL_CUSTOMER_ID,
    CCV.REGION_CODE,
    MAX(CCV.CONTRACT_VERSION_NUMBER) AS MAX_CONTRACT_VERSION_NUMBER,
    MAX(CNSV.MARKET_SEGMENT_SUBTYPE_CODE) AS MARKET_SEGMENT_SUBTYPE_CODE,
    MAX(CNSV.MARKET_SEGMENT_TYPE_CODE) AS MARKET_SEGMENT_TYPE_CODE,
    MAX(CNSV.REGIONAL_CUSTOMER_NAME) AS REGIONAL_CUSTOMER_NAME,
    MAX(CNSV.MARKET_SEGMENT_DIVISION_CODE) AS MARKET_SEGMENT_DIVISION_CODE
  FROM
    CONTRACT_OWNER.CAC_CONTRACT_VERSION CCV
    INNER JOIN CAC_CORRECT_MARKET_SEGMENT_DIVISIONS CNSV ON CCV.REGION_CODE = CNSV.REGION_CODE
    AND CCV.REGIONAL_CUSTOMER_ID = CNSV.REGIONAL_CUSTOMER_ID
  GROUP BY
    CCV.CONTRACT_ID,
    CCV.REGIONAL_CUSTOMER_ID,
    CCV.REGION_CODE
),
CAC_RECENT_CALC_PLAN_RATE_ASSOCIATION AS (
  SELECT
    SOLD_PLAN_ID,
    REGION_CODE,
    RATE_ID,
    MAX(EFFECTIVE_DATE) AS MAX_EFFECTIVE_DATE
  FROM
    PLAN_OWNER.CAC_PLAN_RATE_ASSOCIATION CPRA
  GROUP BY
    SOLD_PLAN_ID,
    REGION_CODE,
    RATE_ID
),
CAC_PLAN_NUMBER AS (
  SELECT
    CPO.REGION_CODE,
    CPO.REGIONAL_CUSTOMER_ID,
    CPO.CONTRACT_ID,
    CPO.PLAN_OFFERING_ID,
    CPO.ELIGIBILITY_SUBGROUP_ID,
    CPO.CONTRACT_VERSION_NUMBER,
    CPO.SOLD_PLAN_ID,
    CPO.SOLD_PLAN_ID AS CAC_PLAN,
    CSPM.EPP_ID,
    CPO.REGION_CODE || CPO.REGIONAL_CUSTOMER_ID || '-' ||
    CPO.ELIGIBILITY_SUBGROUP_ID || '-' ||
    CPO.PLAN_OFFERING_ID || '-' ||
    CSPM.COVERAGE_TYPE || '-' ||
    CSPM.EMPLOYER_POS AS PPG_CAC_UNIQUE_MATCH,
    CPO.NAME,
    CSPM.ALT_ID_SUFFIX,
    MV.MARKET_SEGMENT_SUBTYPE_CODE,
    MV.MARKET_SEGMENT_TYPE_CODE,
    MV.REGIONAL_CUSTOMER_NAME,
    MV.MARKET_SEGMENT_DIVISION_CODE
  FROM CONTRACT_OWNER.CAC_PLAN_OFFERING CPO
  INNER JOIN CAC_MAX_VERSION MV
    ON CPO.CONTRACT_ID = MV.CONTRACT_ID
   AND CPO.REGIONAL_CUSTOMER_ID = MV.REGIONAL_CUSTOMER_ID
   AND CPO.REGION_CODE = MV.REGION_CODE
   AND CPO.CONTRACT_VERSION_NUMBER = MV.MAX_CONTRACT_VERSION_NUMBER
  INNER JOIN PLAN_OWNER.CAC_SOLD_PLAN_MATRIX CSPM
    ON CPO.REGION_CODE = CSPM.REGION_CODE
   AND CPO.SOLD_PLAN_ID = CSPM.SOLD_PLAN_ID
),
CAC_NATIONAL_CUSTOMER AS (
  SELECT
    REGION_CODE,
    REGIONAL_CUSTOMER_ID,
    NATIONAL_CUSTOMER_ID,
    CUSTOMER_SIZE
  FROM
    CAC_REGIONAL_CUSTOMER
),
CAC_PLAN_JURISDICTION AS (
  SELECT
    SOLD_PLAN_ID,
    REGION_CODE,
    JURISDICTION
  FROM
    PLAN_OWNER.CAC_PLAN
),
EPIC_PLAN_GROUP AS (
  SELECT
    PLAN_GROUP_ID,
    PPG_CAC_UNIQUE_MATCH,
    NATIONAL_CUSTOMER_ID,
    REGIONAL_CUSTOMER_ID
  FROM
    MEMBER_OWNER.TAP_PLAN_GROUP
  WHERE
    PPG_CAC_UNIQUE_MATCH IS NOT NULL
),
EPIC_ALTERNATE_INFORMATION AS (
  SELECT
    *
  FROM
    (
      SELECT
        TAG.PLAN_GROUP_ID,
        TPG.PPG_CAC_UNIQUE_MATCH,
        TAG.ALTERNATE_INFO_TYPE_CODE,
        TAG.ALTERNATE_INFORMATION
      FROM
        MEMBER_OWNER.TAP_ALTERNATE_GROUP TAG
        INNER JOIN MEMBER_OWNER.TAP_PLAN_GROUP TPG ON TAG.PLAN_GROUP_ID = TPG.PLAN_GROUP_ID
      WHERE
        TAG.ALTERNATE_INFO_TYPE_CODE IN ('ALT_ID', 'ALT_GROUP_NAME')
    ) PIVOT (
      MAX(ALTERNATE_INFORMATION) FOR ALTERNATE_INFO_TYPE_CODE IN (
        'ALT_ID' AS ALT_ID,
        'ALT_GROUP_NAME' AS ALT_GROUP_NAME
      )
    )
),
STATE_GEO_CROSSWALK AS (
  SELECT
    *
  FROM
    COMMON_OWNER.CROSS_WALK
  WHERE
    selector_code = 'STATE_TO_GEOGRAPHIC_AREA'
),
ALL_ATTRIBUTES AS(
  SELECT
    PN.PPG_CAC_UNIQUE_MATCH AS PPG_CAC_UNIQUE_MATCH_CAC,
    PG.PPG_CAC_UNIQUE_MATCH AS PPG_CAC_UNIQUE_MATCH_EPIC,
    PN.CAC_PLAN AS CAC_PLAN,
CASE
  WHEN TBP.EXTERNAL_BENEFIT_PLAN_ID IS NOT NULL
  THEN 'PRESENT'
  ELSE 'NOT PRESENT'
END AS EPIC_PLAN,
    PN.REGIONAL_CUSTOMER_ID AS REGIONAL_CUSTOMER_ID_CAC,
    PG.REGIONAL_CUSTOMER_ID AS REGIONAL_CUSTOMER_ID_EPIC,
    NC.NATIONAL_CUSTOMER_ID AS NATIONAL_CUSTOMER_ID_CAC,
    NC.NATIONAL_CUSTOMER_ID AS NATIONAL_CUSTOMER_ID_EPIC,
    NC.CUSTOMER_SIZE,
    CASE
      WHEN (
        PN.REGION_CODE = 'NCR'
        OR PN.REGION_CODE = 'SCR'
      ) THEN PN.REGIONAL_CUSTOMER_ID || '-' || PN.ELIGIBILITY_SUBGROUP_ID || '-' || PN.PLAN_OFFERING_ID
      ELSE PN.REGIONAL_CUSTOMER_ID || '*' || PN.ELIGIBILITY_SUBGROUP_ID || PN.ALT_ID_SUFFIX
    END AS ALT_ID_CAC,
    AI.ALT_ID AS ALT_ID_EPIC,
    PN.REGIONAL_CUSTOMER_NAME AS ALT_GROUP_NAME_CAC,
    AI.ALT_GROUP_NAME AS ALT_GROUP_NAME_EPIC,
    CASE
      WHEN NC.CUSTOMER_SIZE = 'Individual' THEN 1
      WHEN NC.CUSTOMER_SIZE = 'Small' THEN 20
      WHEN NC.CUSTOMER_SIZE = 'Large' THEN 100
      ELSE NULL
    END AS COB_GROUP_SIZE_CAC,
    NULL AS COB_GROUP_SIZE_EPIC,
    tgsa.GEOGRAPHIC_SERVICE_AREA_ID AS GEOGRAPHIC_SERVICE_AREA_ID_EPIC,
    CASE
      WHEN PN.name LIKE '%Virtual Plus%'
      AND UPPER(PN.market_segment_division_code) = 'Off Exchange' THEN UPPER(PN.market_segment_division_code) || '^' || PJ.jurisdiction || '^' || 'VP'
      WHEN PN.region_code = 'HAW'
      AND UPPER(PN.market_segment_division_code) = 'Medicaid' THEN UPPER(PN.market_segment_division_code) || '^' || PJ.jurisdiction || '^' || PN.regional_customer_id || '^' || PN.eligibility_subgroup_id
      WHEN UPPER(PN.market_segment_division_code) = 'Medicaid' THEN UPPER(PN.market_segment_division_code) || '^' || PJ.jurisdiction || '^' || PN.regional_customer_id
      WHEN PN.region_code = 'COL' THEN UPPER(PN.market_segment_division_code) || '^' || PJ.jurisdiction || '^' || 'DEFAULT2' -- incomplete. Need to follow up on step 4 in mapping document
      ELSE UPPER(PN.market_segment_division_code) || '^' || PJ.jurisdiction || '^' || 'DEFAULT'
    END AS GEOGRAPHIC_SERVICE_AREA_ID_CAC,
    tgsa.GEOGRAPHIC_SERVICE_AREA_NAME AS GEOGRAPHIC_SERVICE_AREA_NAME_EPIC,
    'INTERNAL' AS GEOGRAPHIC_SERVICE_AREA_ID_TYPE_CAC,
    'INTERNAL' AS GEOGRAPHIC_SERVICE_AREA_ID_TYPE_EPIC,
    'Y' AS NON_PREFERRED_AREA_IND_CAC,
    tpgnpga.NON_PREFERRED_AREA_IND AS NON_PREFERRED_AREA_IND_EPIC
  FROM
    CAC_PLAN_NUMBER PN
    LEFT JOIN CAC_NATIONAL_CUSTOMER NC ON PN.REGION_CODE = NC.REGION_CODE
    AND PN.REGIONAL_CUSTOMER_ID = NC.REGIONAL_CUSTOMER_ID
    LEFT JOIN EPIC_PLAN_GROUP PG ON PN.PPG_CAC_UNIQUE_MATCH = PG.PPG_CAC_UNIQUE_MATCH
    LEFT JOIN EPIC_ALTERNATE_INFORMATION AI ON PG.PLAN_GROUP_ID = AI.PLAN_GROUP_ID
    LEFT JOIN MEMBER_OWNER.TAP_PLAN_GROUP_NON_PREFERRED_GEO_AREA tpgnpga ON PG.plan_group_id = tpgnpga.plan_group_id
    LEFT JOIN MEMBER_OWNER.TAP_GEOGRAPHIC_SERVICE_AREA tgsa ON tpgnpga.GEOGRAPHIC_SERVICE_AREA_ID = tgsa.GEOGRAPHIC_SERVICE_AREA_ID
    LEFT JOIN MEMBER_OWNER.TAP_BENEFIT_PLAN TBP  ON PN.EPP_ID = TBP.EXTERNAL_BENEFIT_PLAN_ID
    LEFT JOIN CAC_PLAN_JURISDICTION PJ ON PN.SOLD_PLAN_ID = PJ.SOLD_PLAN_ID
    AND PN.REGION_CODE = PJ.REGION_CODE -- Filters (adjust or uncomment as needed)
  WHERE
    --    NC.CUSTOMER_SIZE IS NOT NULL
    PN.PPG_CAC_UNIQUE_MATCH IS NOT NULL
    AND PG.PPG_CAC_UNIQUE_MATCH IS NOT NULL
    AND PN.REGION_CODE = :region
)
SELECT
  AA.PPG_CAC_UNIQUE_MATCH_CAC,
  AA.PPG_CAC_UNIQUE_MATCH_EPIC,
  CASE
    WHEN AA.PPG_CAC_UNIQUE_MATCH_CAC IS NULL
    AND AA.PPG_CAC_UNIQUE_MATCH_EPIC IS NULL THEN 'MATCH'
    WHEN AA.PPG_CAC_UNIQUE_MATCH_CAC = AA.PPG_CAC_UNIQUE_MATCH_EPIC THEN 'MATCH'
    ELSE 'MISMATCH'
  END AS CMP_PPG_CAC_UNIQUE_MATCH,
  AA.CAC_PLAN,  AA.EPIC_PLAN,
  CASE  WHEN AA.EPIC_PLAN = 'PRESENT'  THEN 'MATCH'  ELSE 'MISMATCH' END AS CMP_EPIC_PLAN,
  AA.REGIONAL_CUSTOMER_ID_CAC,
  AA.REGIONAL_CUSTOMER_ID_EPIC,
  CASE
    WHEN AA.REGIONAL_CUSTOMER_ID_CAC IS NULL
    AND AA.REGIONAL_CUSTOMER_ID_EPIC IS NULL THEN 'MATCH'
    WHEN AA.REGIONAL_CUSTOMER_ID_CAC = AA.REGIONAL_CUSTOMER_ID_EPIC THEN 'MATCH'
    ELSE 'MISMATCH'
  END AS CMP_REGIONAL_CUSTOMER_ID,
  AA.NATIONAL_CUSTOMER_ID_CAC,
  AA.NATIONAL_CUSTOMER_ID_EPIC,
  CASE
    WHEN AA.NATIONAL_CUSTOMER_ID_CAC IS NULL
    AND AA.NATIONAL_CUSTOMER_ID_EPIC IS NULL THEN 'MATCH'
    WHEN AA.NATIONAL_CUSTOMER_ID_CAC = AA.NATIONAL_CUSTOMER_ID_EPIC THEN 'MATCH'
    ELSE 'MISMATCH'
  END AS CMP_NATIONAL_CUSTOMER_ID,
  AA.CUSTOMER_SIZE,
  AA.ALT_ID_CAC,
  AA.ALT_ID_EPIC,
  CASE
    WHEN AA.ALT_ID_CAC IS NULL
    AND AA.ALT_ID_EPIC IS NULL THEN 'MATCH'
    WHEN AA.ALT_ID_CAC = AA.ALT_ID_EPIC THEN 'MATCH'
    ELSE 'MISMATCH'
  END AS CMP_ALT_ID,
  AA.ALT_GROUP_NAME_CAC,
  AA.ALT_GROUP_NAME_EPIC,
  CASE
    WHEN AA.ALT_GROUP_NAME_CAC IS NULL
    AND AA.ALT_GROUP_NAME_EPIC IS NULL THEN 'MATCH'
    WHEN AA.ALT_GROUP_NAME_CAC = AA.ALT_GROUP_NAME_EPIC THEN 'MATCH'
    ELSE 'MISMATCH'
  END AS CMP_ALT_GROUP_NAME,
  AA.COB_GROUP_SIZE_CAC,
  AA.COB_GROUP_SIZE_EPIC,
  CASE
    WHEN AA.COB_GROUP_SIZE_CAC IS NULL
    AND AA.COB_GROUP_SIZE_EPIC IS NULL THEN 'MATCH'
    WHEN AA.COB_GROUP_SIZE_CAC = AA.COB_GROUP_SIZE_EPIC THEN 'MATCH'
    ELSE 'MISMATCH'
  END AS CMP_COB_GROUP_SIZE,
  AA.GEOGRAPHIC_SERVICE_AREA_ID_EPIC,
  CASE
    WHEN LK.FROM_VALUE IS NOT NULL THEN LK.TO_VALUE
    ELSE AA.GEOGRAPHIC_SERVICE_AREA_ID_CAC
  END AS GEOGRAPHIC_SERVICE_AREA_ID_CAC,
  CASE
    WHEN AA.GEOGRAPHIC_SERVICE_AREA_ID_EPIC IS NULL
    AND (
      CASE
        WHEN LK.FROM_VALUE IS NOT NULL THEN LK.TO_VALUE
        ELSE AA.GEOGRAPHIC_SERVICE_AREA_ID_CAC
      END
    ) IS NULL THEN 'MATCH'
    WHEN AA.GEOGRAPHIC_SERVICE_AREA_ID_EPIC = CASE
      WHEN LK.FROM_VALUE IS NOT NULL THEN LK.TO_VALUE
      ELSE AA.GEOGRAPHIC_SERVICE_AREA_ID_CAC
    END THEN 'MATCH'
    ELSE 'MISMATCH'
  END AS CMP_GEOGRAPHIC_SERVICE_AREA_ID,
  AA.GEOGRAPHIC_SERVICE_AREA_NAME_EPIC,
  AA.GEOGRAPHIC_SERVICE_AREA_ID_TYPE_CAC,
  AA.GEOGRAPHIC_SERVICE_AREA_ID_TYPE_EPIC,
  CASE
    WHEN AA.GEOGRAPHIC_SERVICE_AREA_ID_TYPE_CAC IS NULL
    AND AA.GEOGRAPHIC_SERVICE_AREA_ID_TYPE_EPIC IS NULL THEN 'MATCH'
    WHEN AA.GEOGRAPHIC_SERVICE_AREA_ID_TYPE_CAC = AA.GEOGRAPHIC_SERVICE_AREA_ID_TYPE_EPIC THEN 'MATCH'
    ELSE 'MISMATCH'
  END AS CMP_GEOGRAPHIC_SERVICE_AREA_ID_TYPE,
  AA.NON_PREFERRED_AREA_IND_CAC,
  AA.NON_PREFERRED_AREA_IND_EPIC,
  CASE
    WHEN AA.NON_PREFERRED_AREA_IND_CAC IS NULL
    AND AA.NON_PREFERRED_AREA_IND_EPIC IS NULL THEN 'MATCH'
    WHEN AA.NON_PREFERRED_AREA_IND_CAC = AA.NON_PREFERRED_AREA_IND_EPIC THEN 'MATCH'
    ELSE 'MISMATCH'
  END AS CMP_NON_PREFERRED_AREA_IND
FROM
  ALL_ATTRIBUTES AA
  LEFT JOIN STATE_GEO_CROSSWALK LK ON AA.GEOGRAPHIC_SERVICE_AREA_ID_CAC = LK.FROM_VALUE