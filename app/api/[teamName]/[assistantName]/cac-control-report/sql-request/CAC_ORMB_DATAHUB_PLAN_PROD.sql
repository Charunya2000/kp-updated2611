  -- COMPARISIONS
  VACC.CAC_AGE_CALCULATION_DATE_BASIS_RULE,
  PPRC.ORMB_AGE_CALCULATION_DATE_BASIS_RULE,
  CASE
    WHEN PPRC.ORMB_AGE_CALCULATION_DATE_BASIS_RULE IS NULL
    AND VACC.CAC_AGE_CALCULATION_DATE_BASIS_RULE IS NULL THEN 'MATCH'
    WHEN PPRC.ORMB_AGE_CALCULATION_DATE_BASIS_RULE = VACC.CAC_AGE_CALCULATION_DATE_BASIS_RULE THEN 'MATCH'
    ELSE 'NO MATCH'
  END AS AGE_CALCULATION_DATE_BASIS_RULE_COMPARISON,
  'BIL-G101-MENURATE' AS CAC_RATING_METHOD_BILLING,
  --verified
  PPRC.ORMB_RATING_METHOD_BILLING,
  CASE
    WHEN 'BIL-G101-MENURATE' = PPRC.ORMB_RATING_METHOD_BILLING THEN 'MATCH'
    ELSE 'NO MATCH'
  END AS RATING_METHOD_BILLING_COMPARISON,
  VWPC.CAC_WASH_PRORATION_ENROLLMENT,
  PPRC.ORMB_WASH_PRORATION_ENROLLMENT,
  CASE
    WHEN PPRC.ORMB_WASH_PRORATION_ENROLLMENT IS NULL
    AND VWPC.CAC_WASH_PRORATION_ENROLLMENT IS NULL THEN 'MATCH'
    WHEN PPRC.ORMB_WASH_PRORATION_ENROLLMENT = VWPC.CAC_WASH_PRORATION_ENROLLMENT THEN 'MATCH'
    ELSE 'NO MATCH'
  END AS WASH_PRORATION_ENROLLMENT_COMPARISON,
  'N' CAC_PROMOTION_RULE,
  --verified TODO: switch to NULL
  PPRC.ORMB_PROMOTION_RULE,
  CASE
    WHEN 'N' = PPRC.ORMB_PROMOTION_RULE THEN 'MATCH'
    ELSE 'NO MATCH'
  END AS PROMOTION_RULE_COMPARISON,
  PPRC.RATE_STRUCTURE CAC_RATE_STRUCTURE_CODE,
  PPRC.ORMB_RATE_STRUCTURE_CODE,
  CASE
    WHEN PPRC.RATE_STRUCTURE = PPRC.ORMB_RATE_STRUCTURE_CODE THEN 'MATCH'
    ELSE 'NO MATCH'
  END AS RATE_STRUCTURE_CODE_COMPARISON,
  PPRC.GRANDFATHERED_INDICATOR CAC_GRANDFATHERED_INDICATOR,
  PPRC.ORMB_GRANDFATHERED_INDICATOR,
  CASE
    WHEN PPRC.GRANDFATHERED_INDICATOR = PPRC.ORMB_GRANDFATHERED_INDICATOR THEN 'MATCH'
    ELSE 'NO MATCH'
  END AS GRANDFATHERED_INDICATOR_COMPARISON,
  UPPER(
    PPRC.MARKET_SEGMENT || '-' || PPRC.DIVISION || '-' || PPRC.HEALTHCARE_CATEGORY_NAME
  ) AS CAC_PRODUCT_CATEGORY,
  UPPER(PPRC.ORMB_PRODUCT_CATEGORY),
  CASE
    WHEN UPPER(
      PPRC.MARKET_SEGMENT || '-' || PPRC.DIVISION || '-' || PPRC.HEALTHCARE_CATEGORY_NAME
    ) = UPPER(PPRC.ORMB_PRODUCT_CATEGORY) THEN 'MATCH'
    ELSE 'NO MATCH'
  END AS PRODUCT_CATEGORY_COMPARISON,
  UPPER(
    PPRC.HEALTHCARE_CATEGORY_NAME || '-' || PPRC.UNDERWRITER_ORG_NAME
  ) AS CAC_PRODUCT_SUB_CATEGORY,
  UPPER(PPRC.ORMB_PRODUCT_SUB_CATEGORY),
  CASE
    WHEN UPPER(
      PPRC.HEALTHCARE_CATEGORY_NAME || '-' || PPRC.UNDERWRITER_ORG_NAME
    ) = UPPER(PPRC.ORMB_PRODUCT_SUB_CATEGORY) THEN 'MATCH'
    ELSE 'NO MATCH'
  END AS PRODUCT_SUB_CATEGORY_COMPARISON,
  UPPER(
    PPRC.UNDERWRITER_ORG_NAME || '-' || PPRC.PRODUCT_TYPE_NAME || '-' || PPRC.HEALTHCARE_CATEGORY_NAME
  ) AS CAC_PRODUCT_TYPE,
  UPPER(PPRC.ORMB_PRODUCT_TYPE),
  CASE
    WHEN UPPER(
      PPRC.UNDERWRITER_ORG_NAME || '-' || PPRC.PRODUCT_TYPE_NAME || '-' || PPRC.HEALTHCARE_CATEGORY_NAME
    ) = UPPER(PPRC.ORMB_PRODUCT_TYPE) THEN 'MATCH'
    ELSE 'NO MATCH'
  END AS PRODUCT_TYPE_COMPARISON
FROM
  WITH_ALIASES PPRC
  LEFT JOIN VALID_AGE_CALC_CONTRACTS VACC ON PPRC.REGION_CODE = VACC.REGION_CODE
  AND PPRC.REGIONAL_CUSTOMER_ID = VACC.REGIONAL_CUSTOMER_ID
  AND PPRC.CONTRACT_ID = VACC.CONTRACT_ID
  AND VACC.ELIGIBILITY_SUBGROUP_ID = VACC.ELIGIBILITY_SUBGROUP_ID
  LEFT JOIN VALID_WASH_PRORATION_CONTRACTS VWPC ON PPRC.REGION_CODE = VWPC.REGION_CODE
  AND PPRC.REGIONAL_CUSTOMER_ID = VWPC.REGIONAL_CUSTOMER_ID
  AND PPRC.CONTRACT_ID = VWPC.CONTRACT_ID
  AND PPRC.PLAN_OFFERING_ID = VWPC.PLAN_OFFERING_ID
