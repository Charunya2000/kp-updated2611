PRODUCT_INFO AS -- GOOD
(
  SELECT
    PN.PLAN_NBR,
    RCPRA.RATE_ID,
    PN.REGION_CODE,
    PN.REGIONAL_CUSTOMER_ID,
    PN.CONTRACT_ID,
    PN.PLAN_OFFERING_ID,
    PN.ELIGIBILITY_SUBGROUP_ID,
    PN.CONTRACT_VERSION_NUMBER,
    PN.SOLD_PLAN_ID,
    RCPRA.MAX_EFFECTIVE_DATE,
    CR.MARKET_SEGMENT_TYPE_CODE,
    CR.RATE_STRUCTURE,
    PPU.NETWORK_TIER_NAME,
    PPU.UNDERWRITER_ORG_NAME,
    CP.GRANDFATHERED_INDICATOR,
    RMS.MARKET_SEGMENT,
    RMS.DIVISION,
    HIP.HEALTHCARE_CATEGORY_NAME,
    HIP.PRODUCT_TYPE_NAME
  FROM
    PLAN_NUMBER PN
    INNER JOIN RECENT_CALC_PLAN_RATE_ASSOCIATION RCPRA ON PN.REGION_CODE = RCPRA.REGION_CODE
    AND PN.SOLD_PLAN_ID = RCPRA.SOLD_PLAN_ID
    INNER JOIN PLAN_OWNER.CAC_PLAN CP ON PN.SOLD_PLAN_ID = CP.SOLD_PLAN_ID
    AND PN.REGION_CODE = CP.REGION_CODE
    INNER JOIN PLAN_OWNER.CAC_RATE CR ON RCPRA.RATE_ID = CR.RATE_ID
    INNER JOIN PRODUCT_OWNER.PRD_HEALTH_INSURANCE_PRODUCT HIP ON CP.PRODUCT_ID = HIP.PRODUCT_ID
    INNER JOIN -- WORRISOME JOIN
    PRODUCT_OWNER.PRD_PRODUCT_UNDERWRITER PPU ON CP.PRODUCT_ID = PPU.PRODUCT_ID
    AND CP.REGION_CODE = PPU.REGION_CODE
    INNER JOIN PRODUCT_OWNER.PRD_PRODUCT_BY_MARKET_SEGMENT RMS ON CP.PRODUCT_ID = RMS.PRODUCT_ID
    AND CR.MARKET_SEGMENT_TYPE_CODE = RMS.MARKET_SEGMENT
    AND CR.MARKET_SEGMENT_DIVISION_CODE = RMS.DIVISION
  WHERE
    CP.REGION_CODE = :region
