PLAN_NUMBER AS -- GOOD
(
  SELECT
    CPO.REGION_CODE,
    CPO.REGIONAL_CUSTOMER_ID,
    CPO.CONTRACT_ID,
    CPO.PLAN_OFFERING_ID,
    CPO.ELIGIBILITY_SUBGROUP_ID,
    CPO.CONTRACT_VERSION_NUMBER,
    CPO.SOLD_PLAN_ID,
    CPO.REGION_CODE || '-' || CPO.REGIONAL_CUSTOMER_ID || '-' || CPO.CONTRACT_ID || '-' || CPO.PLAN_OFFERING_ID || '-' || CPO.ELIGIBILITY_SUBGROUP_ID PLAN_NBR
  FROM
    CONTRACT_OWNER.CAC_PLAN_OFFERING CPO
    INNER JOIN MAX_VERSION MV ON CPO.CONTRACT_ID = MV.CONTRACT_ID
    AND CPO.REGIONAL_CUSTOMER_ID = MV.REGIONAL_CUSTOMER_ID
    AND CPO.REGION_CODE = MV.REGION_CODE
    AND CPO.CONTRACT_VERSION_NUMBER = MV.MAX_CONTRACT_VERSION_NUMBER
